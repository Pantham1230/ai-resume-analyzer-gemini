import { Button } from "@/components/ui/button";
import { Download } from "lucide-react";

export function PdfExport({ results }: { results: any }) {
  const handleExport = () => {
    const lines: string[] = [];
    const add = (text: string) => lines.push(text);
    const blank = () => lines.push("");

    add("═══════════════════════════════════════════");
    add("          AI RESUME ANALYSIS REPORT");
    add("═══════════════════════════════════════════");
    blank();

    add(`MATCH SCORE: ${results.matchScore}%`);
    blank();

    if (results.scoreBreakdown) {
      add("── SCORE BREAKDOWN ──");
      const labels: Record<string, string> = {
        skillMatch: "Skill Match",
        experienceRelevance: "Experience",
        projects: "Projects",
        education: "Education",
        atsKeywordPresence: "ATS Keywords",
      };
      for (const [key, item] of Object.entries(results.scoreBreakdown) as any) {
        add(`  ${labels[key] || key}: ${item.score}/${item.maxScore} — ${item.details}`);
      }
      blank();
    }

    if (results.extractedSkills) {
      add("── EXTRACTED SKILLS ──");
      const cats: Record<string, string> = {
        programming: "Programming",
        aiMl: "AI/ML",
        toolsFrameworks: "Tools & Frameworks",
        databases: "Databases",
        softSkills: "Soft Skills",
        other: "Other",
      };
      for (const [key, skills] of Object.entries(results.extractedSkills) as any) {
        if (skills?.length) add(`  ${cats[key] || key}: ${skills.join(", ")}`);
      }
      blank();
    }

    if (results.matchingSkills?.length) {
      add("── MATCHING SKILLS ──");
      add(`  ${results.matchingSkills.join(", ")}`);
      blank();
    }

    if (results.missingSkills?.length) {
      add("── MISSING SKILLS ──");
      add(`  ${results.missingSkills.join(", ")}`);
      blank();
    }

    if (results.strengths?.length) {
      add("── STRENGTHS ──");
      results.strengths.forEach((s: string) => add(`  ✓ ${s}`));
      blank();
    }

    if (results.weaknesses?.length) {
      add("── WEAKNESSES ──");
      results.weaknesses.forEach((s: string) => add(`  ✗ ${s}`));
      blank();
    }

    if (results.sectionEvaluation?.length) {
      add("── SECTION EVALUATION ──");
      results.sectionEvaluation.forEach((s: any) => {
        add(`  ${s.section} [${s.strength}]`);
        add(`    ${s.feedback}`);
        s.suggestions?.forEach((sug: string) => add(`    • ${sug}`));
      });
      blank();
    }

    if (results.atsOptimization) {
      add("── ATS OPTIMIZATION ──");
      if (results.atsOptimization.missingKeywords?.length)
        add(`  Missing: ${results.atsOptimization.missingKeywords.join(", ")}`);
      if (results.atsOptimization.suggestedKeywords?.length)
        add(`  Suggested: ${results.atsOptimization.suggestedKeywords.join(", ")}`);
      results.atsOptimization.formattingTips?.forEach((t: string) => add(`  • ${t}`));
      blank();
    }

    if (results.careerPaths?.length) {
      add("── RECOMMENDED CAREER PATHS ──");
      results.careerPaths.forEach((p: any) => add(`  ${p.role} (${p.matchPercentage}%) — ${p.explanation}`));
      blank();
    }

    if (results.learningResources?.length) {
      add("── LEARNING RESOURCES ──");
      results.learningResources.forEach((lr: any) => {
        add(`  ${lr.skill}:`);
        lr.resources?.forEach((r: any) => add(`    - ${r.name} (${r.platform}) ${r.url}`));
      });
      blank();
    }

    if (results.actionPlan?.length) {
      add("── ACTION PLAN ──");
      results.actionPlan.forEach((s: string, i: number) => add(`  ${i + 1}. ${s}`));
      blank();
    }

    add("═══════════════════════════════════════════");
    add("Generated by ResumeAI — " + new Date().toLocaleDateString());

    const blob = new Blob([lines.join("\n")], { type: "text/plain" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = "resume-analysis-report.txt";
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <Button onClick={handleExport} variant="outline" size="sm" className="rounded-full">
      <Download className="w-4 h-4 mr-1" /> Download Report
    </Button>
  );
}
